"""Builds data/narration.json (what the game reads) from the delivered narration package manifest
(assets/docs/narration/NARRATION_MANIFEST.json, the source of truth for every number).

    python tools/audio/build_narration_map.py

Per cinematic: the music bed and its volume; per slide: the voice clip, when the line starts after
the slide appears (`voice_at`, the bed pre-roll on slide 1), when its subtitle appears
(`subtitle_at` = voice_at + subtitle_sync.start_s) and how long the slide holds (`hold`).

Holds follow the manifest timeline so the bed's hits land where the music was written for them:
a slide lasts until the next line's timeline start (the manifest's dramatic gaps included), and the
last slide until the timeline end card, never less than its line plus MIN_TAIL. The script checks
that every subtitle matches data/cinematics.json verbatim, that every file exists, and that no
hold cuts a line off. It never edits data/cinematics.json.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MANIFEST = os.path.join(ROOT, "assets", "docs", "narration", "NARRATION_MANIFEST.json")
CINEMATICS = os.path.join(ROOT, "data", "cinematics.json")
AUDIO = os.path.join(ROOT, "data", "audio.json")
OUT = os.path.join(ROOT, "data", "narration.json")
## Silence kept after the last line of a cinematic before its end card (owner: "about 1 second").
MIN_TAIL = 1.0
## Live duck matching the package's duck envelopes (attack 120 ms, hold 250 ms, release 600 ms, 9 dB).
DUCK = {"duck_db": 9.0, "duck_attack_s": 0.12, "duck_hold_s": 0.25, "duck_release_s": 0.6}
## Beds are mastered like the other cinematic scores, so they use the same level as the "cinematic" cue.
BED_CUE = "cinematic"


def res(path: str) -> str:
    return path if path.startswith("res://") else "res://" + path.replace("\\", "/")


def main() -> int:
    with open(MANIFEST, encoding="utf-8") as f:
        manifest = json.load(f)
    with open(CINEMATICS, encoding="utf-8") as f:
        sequences = {s["id"]: s for s in json.load(f)["sequences"]}
    with open(AUDIO, encoding="utf-8") as f:
        bed_volume = float(json.load(f)["music"][BED_CUE]["volume_db"])
    problems = []
    out = {}
    for cinematic in manifest["cinematics"]:
        sid = cinematic["cinematic_id"]
        sequence = sequences.get(sid)
        if sequence is None:
            problems.append(f"{sid}: not in data/cinematics.json")
            continue
        slides = sorted(cinematic["slides"], key=lambda s: s["slide_index"])
        if [s["slide_index"] for s in slides] != list(range(len(sequence["slides"]))):
            problems.append(f"{sid}: manifest slides do not cover every slide once")
            continue
        bed = cinematic["music_bed"]
        if not os.path.exists(os.path.join(ROOT, bed)):
            problems.append(f"{sid}: missing bed {bed}")
        starts = [float(s["timeline"]["voice_start_s"]) for s in slides]
        last_end = float(slides[-1]["timeline"]["voice_end_s"])
        end_card = max(float(cinematic["timeline"]["end_card_s"]), last_end + MIN_TAIL)
        entries = []
        for i, s in enumerate(slides):
            if s["text"] != sequence["slides"][i]["subtitle"]:
                problems.append(f"{sid}/{i + 1}: manifest text differs from the subtitle")
            if not os.path.exists(os.path.join(ROOT, s["file"])):
                problems.append(f"{sid}/{i + 1}: missing {s['file']}")
            stage_start = 0.0 if i == 0 else starts[i]
            stage_end = starts[i + 1] if i + 1 < len(slides) else end_card
            voice_at = round(starts[i] - stage_start, 3)
            hold = round(stage_end - stage_start, 3)
            duration = float(s["duration_s"])
            if hold < voice_at + duration + MIN_TAIL - 0.001:
                problems.append(f"{sid}/{i + 1}: hold {hold} s would cut the {duration} s line")
            entries.append({
                "voice": res(s["file"]),
                "duration": round(duration, 3),
                "voice_at": voice_at,
                "subtitle_at": round(voice_at + float(s["subtitle_sync"]["start_s"]), 3),
                "hold": hold,
            })
        out[sid] = {"bed": res(bed), "bed_volume_db": bed_volume, "slides": entries}
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    data = {
        "status": "integrated",
        "note": "Generated by tools/audio/build_narration_map.py from assets/docs/narration/NARRATION_MANIFEST.json; do not edit by hand. Rights: commercially usable per provider terms, not legally cleared, pending the owner's review (assets/docs/narration/LICENSING_PROVENANCE.md).",
        "bus": "Voice",
        **DUCK,
        "sequences": out,
    }
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(data, indent="\t", ensure_ascii=False) + "\n")
    lines = sum(len(s["slides"]) for s in out.values())
    print(f"{len(out)} cinematics, {lines} voiced slides -> data/narration.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())

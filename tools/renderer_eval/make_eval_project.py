#!/usr/bin/env python3
"""Create an isolated renderer-evaluation copy of the project (M3).

The copy has the benchmark as its main scene, the requested renderer, its own user-data folder and
its own Android package ID, so it can be installed next to the real game. The production
project.godot and export presets are never modified.

    python tools/renderer_eval/make_eval_project.py --variant mobile --out ../temporal-eval-mobile
    python tools/renderer_eval/make_eval_project.py --variant compatibility --out ../temporal-eval-compat --soak-minutes 10

Then:
    godot_console --path <out> --headless --import
    godot_console --path <out>                          # desktop smoke run
    godot_console --path <out> --headless --export-debug "Android Eval" <out>/build/eval.apk
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]

VARIANTS = {
    # rendering_method, config/features renderer tag
    "compatibility": ("gl_compatibility", "GL Compatibility"),
    "mobile": ("mobile", "Mobile"),
}

EVAL_PACKAGE = "dev.imrn.temporal1.rendereval"

ANDROID_PRESET = """[preset.0]

name="Android Eval"
platform="Android"
runnable=true
dedicated_server=false
custom_features=""
export_filter="all_resources"
include_filter="data/*.json, tools/renderer_eval/*.json"
exclude_filter="tests/*, docs/*"
export_path="build/eval.apk"
encryption_include_filters=""
encryption_exclude_filters=""
encrypt_pck=false
encrypt_directory=false

[preset.0.options]

gradle_build/use_gradle_build=false
architectures/armeabi-v7a=false
architectures/arm64-v8a=true
architectures/x86=false
architectures/x86_64=true
version/code=1
version/name=""
package/unique_name="{package}"
package/name="Temporal Eval ({label})"
package/signed=true
screen/immersive_mode=true
permissions/vibrate=true
"""


def set_setting(text: str, section: str, key: str, value: str) -> str:
    """Replace key=value inside [section], or append it to the section."""
    pattern = re.compile(rf"^{re.escape(key)}=.*$", re.MULTILINE)
    if pattern.search(text):
        return pattern.sub(lambda _m: f"{key}={value}", text, count=1)
    header = f"[{section}]\n"
    if header not in text:
        return text.rstrip("\n") + f"\n\n{header}\n{key}={value}\n"
    return text.replace(header, f"{header}\n{key}={value}", 1)


def tracked_files() -> list[str]:
    out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"], cwd=REPO, check=True, capture_output=True, text=True)
    return [line for line in out.stdout.splitlines() if line]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--variant", choices=sorted(VARIANTS), required=True)
    parser.add_argument("--out", required=True, help="output folder (must not be inside the repository)")
    parser.add_argument("--soak-minutes", type=float, default=0.0)
    parser.add_argument("--main", default="res://tools/renderer_eval/benchmark.tscn",
                        help="main scene of the isolated copy (e.g. res://tools/regression/score_replay.tscn)")
    args = parser.parse_args()

    out = Path(args.out).resolve()
    if out == REPO or REPO in out.parents:
        print("error: --out must be outside the repository", file=sys.stderr)
        return 2
    if out.exists() and any(out.iterdir()) and not (out / ".renderer_eval").exists():
        print(f"error: {out} exists and is not a previous eval project; refusing to overwrite", file=sys.stderr)
        return 2

    for rel in tracked_files():
        if rel.startswith("docs/"):
            continue
        dest = out / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(REPO / rel, dest)
    (out / ".renderer_eval").write_text("generated by tools/renderer_eval/make_eval_project.py\n")

    method, feature = VARIANTS[args.variant]
    project = (out / "project.godot").read_text(encoding="utf-8")
    project = set_setting(project, "application", "config/name", f'"Temporal Eval ({args.variant})"')
    project = set_setting(project, "application", "run/main_scene", f'"{args.main}"')
    project = set_setting(project, "application", "config/custom_user_dir_name", f'"temporal_renderer_eval_{args.variant}"')
    project = set_setting(project, "application", "config/features", f'PackedStringArray("4.7", "{feature}")')
    project = set_setting(project, "rendering", "renderer/rendering_method", f'"{method}"')
    project = set_setting(project, "rendering", "renderer/rendering_method.mobile", f'"{method}"')
    (out / "project.godot").write_text(project, encoding="utf-8", newline="\n")

    config = {"variant": args.variant, "soak_minutes": args.soak_minutes}
    (out / "tools/renderer_eval/benchmark_config.json").write_text(json.dumps(config, indent=2) + "\n")
    (out / "export_presets.cfg").write_text(
        ANDROID_PRESET.replace("{package}", EVAL_PACKAGE).replace("{label}", args.variant), newline="\n"
    )
    print(f"eval project ({args.variant}, renderer {method}) written to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

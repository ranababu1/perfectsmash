"""Rights audit of everything the release ships (plan revision 7: never alter or clear rights fields).

    python tools/release/rights_audit.py
Reads docs/release/shipped-assets.json (from tools/release/export_manifest.gd) and
assets/asset_manifest.json, and writes docs/release/rights-audit.md: per shipped file, its manifest
id, rights_status, approval_status and source, grouped and counted, with every asset that is not
approved flagged. It only reads the manifest; it never changes it.
"""
import collections
import json

shipped = json.load(open("docs/release/shipped-assets.json", encoding="utf8"))
manifest = json.load(open("assets/asset_manifest.json", encoding="utf8"))
by_path = {}
for entry in manifest["entries"]:
    by_path[entry.get("path", "")] = entry

rows = []
unlisted = []
for res_path in shipped["used"]:
    path = res_path.replace("res://", "")
    entry = by_path.get(path)
    if entry is None:
        unlisted.append(path)
        continue
    rows.append((path, entry))

approval = collections.Counter(e.get("approval_status", "?") for _, e in rows)
rights_kind = collections.Counter()
for _, e in rows:
    r = e.get("rights_status", "?").lower()
    if "ofl" in r or "open font" in r:
        kind = "SIL Open Font License (fonts)"
    elif "unverified" in r:
        kind = "UNVERIFIED"
    elif "ai-generated" in r or "generateimage" in r:
        kind = "AI-generated imagery (not commercially cleared)"
    elif "synthes" in r or "algorithmic composition" in r:
        kind = "Original synthesised audio (AI-assisted authorship)"
    elif "procedural" in r or "code-gener" in r or "authored by the asset agent" in r:
        kind = "Original procedural / code-generated work (AI-assisted authorship)"
    else:
        kind = "Other (see table)"
    rights_kind[kind] += 1

out = []
out.append("# Rights audit — shipped assets (release candidate)\n")
out.append("Generated by `tools/release/rights_audit.py` from `assets/asset_manifest.json` and the export "
           "manifest `docs/release/shipped-assets.json`. This audit **reports** rights and approval data; it never "
           "changes it. **No asset is commercially cleared until the owner approves it** (plan revision 7).\n")
out.append("## Summary\n")
out.append("- Shipped asset files: %d (%.1f MB of sources); manifest entries matched: %d; files without a manifest entry: %d."
           % (len(shipped["used"]), shipped["used_bytes"] / 1048576.0, len(rows), len(unlisted)))
out.append("- Approval status of shipped entries: " + ", ".join("%s %d" % kv for kv in approval.most_common()) + ".")
out.append("- **Release blocker for commercial distribution:** every shipped entry whose approval status is not an owner "
           "approval (all `pending_review` entries) needs the owner's rights review.")
out.append("- Never shipped (excluded from every export preset regardless of references): `assets/audio/music/gameplay_bed.ogg` "
           "and its source `assets/music/bg.mp3` (licence unverified).")
out.append("- Audio re-encoded for size on 2026-11-11 (53 music/ambience files, Vorbis q1, same content and duration); "
           "rights and approval fields unchanged.\n")
out.append("| Rights category | Shipped files |\n|---|---:|")
for kind, count in rights_kind.most_common():
    out.append("| %s | %d |" % (kind, count))
if unlisted:
    out.append("\n## Shipped files without a manifest entry (review)\n")
    for p in sorted(unlisted):
        out.append("- `%s`" % p)
out.append("\n## Every shipped asset\n")
out.append("| File | Manifest id | Approval | Rights (abridged) |\n|---|---|---|---|")
for path, e in sorted(rows):
    rights = e.get("rights_status", "").replace("|", "/").replace("\n", " ")
    if len(rights) > 110:
        rights = rights[:107] + "..."
    flag = "" if e.get("approval_status") in ("approved", "owner_approved") else " ⚠"
    out.append("| `%s` | %s | %s%s | %s |" % (path, e.get("id", ""), e.get("approval_status", ""), flag, rights))
open("docs/release/rights-audit.md", "w", encoding="utf8", newline="\n").write("\n".join(out) + "\n")
print("rights audit: %d shipped, %d matched, %d unlisted; approval %s" % (len(shipped["used"]), len(rows), len(unlisted), dict(approval)))
